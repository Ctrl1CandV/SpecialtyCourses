add('S2-IV03', r'''
    **基本思想。**无向图中从 s 到 t 存在边数不超过 k 的路径，当且仅当最短路边数不超过 k。用 BFS 求最短路和前驱；BFS 第一次到达 t 时得到一条最短路，其 BFS 树路径天然不重复顶点。若 `s=t`，路径只有 s；若 `k<0`，按题意直接失败。逆着前驱回溯后反向写入 `path`。

    ```c
    #include <stddef.h>
    typedef struct Arc {
        int to;
        struct Arc *next;
    } Arc;
    typedef struct {
        int V, E;
        Arc **head;
    } Graph;

    int pathAtMostK(const Graph *G, int s, int t, int k,
                    int *path, int *pathLen) {
        *pathLen = 0;
        if (k < 0) return 0;
        if (s == t) {
            path[0] = s;
            *pathLen = 1;
            return 1;
        }

        int dist[100], parent[100], queue[100], rev[100];
        for (int i = 0; i < G->V; ++i) {
            dist[i] = -1;
            parent[i] = -1;
        }
        int front = 0, rear = 0;
        dist[s] = 0;
        queue[rear++] = s;
        while (front < rear && dist[t] == -1) {
            int u = queue[front++];
            for (const Arc *a = G->head[u]; a != NULL; a = a->next) {
                int v = a->to;
                if (dist[v] != -1) continue;
                dist[v] = dist[u] + 1;
                parent[v] = u;
                queue[rear++] = v;
            }
        }
        if (dist[t] == -1 || dist[t] > k) return 0;

        int len = 0;
        for (int v = t; v != -1; v = parent[v]) rev[len++] = v;
        for (int i = 0; i < len; ++i) path[i] = rev[len - 1 - i];
        *pathLen = len;
        return 1;
    }
    ```

    **复杂度。**BFS 至多扫描 V 个顶点及邻接表中 2E 条弧，时间 O(V+E)；`dist`、`parent`、队列与倒序路径数组合计 O(V) 辅助空间，输出数组由调用者提供。若 `s=t` 或 `k<0`，提前返回为 O(1)。

    **评分建议（12分）：**把存在性化为 BFS 最短路并处理边界2分；初始化、访问与前驱记录5分；限长判断及无重复路径回溯3分；时间与空间复杂度各1分。仅判断可达而未输出合法路径不能取得回溯部分分。
''', ['编译C实现；测试k<0、s=t、孤立点、k恰等于/小于最短距离，以及随机无向图；核对路径首尾、无重复、边数和BFS距离。'])
